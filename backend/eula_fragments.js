// Получить полный текст EULA по языку
export function getFullEula(language = 'EN') {
  return language === 'RU' ? EULA_RU : EULA_EN;
}

// Получить случайную цитату из EULA
export function getRandomEulaQuote(language = 'EN') {
  const quotes = language === 'RU' ? EULA_QUOTES_RU : EULA_QUOTES_EN;
  return quotes[Math.floor(Math.random() * quotes.length)];
}

// Получить несколько цитат
export function getEulaQuotes(count = 5, language = 'EN') {
  const quotes = language === 'RU' ? EULA_QUOTES_RU : EULA_QUOTES_EN;
  const shuffled = [...quotes].sort(() => 0.5 - Math.random());
  return shuffled.slice(0, count);
}

// Поиск по тексту EULA
export function searchEula(keyword, language = 'EN') {
  const fullText = language === 'RU' ? EULA_RU : EULA_EN;
  const lines = fullText.split('\n');
  return lines.filter(line => 
    line.toLowerCase().includes(keyword.toLowerCase())
  );
}

// Статистика EULA
export function eulaStats() {
  return {
    'EN_WORD_COUNT': EULA_EN.split(/\s+/).length,
    'RU_WORD_COUNT': EULA_RU.split(/\s+/).length,
    'EN_QUOTES_COUNT': EULA_QUOTES_EN.length,
    'RU_QUOTES_COUNT': EULA_QUOTES_RU.length,
    'EN_CHARACTERS': EULA_EN.length,
    'RU_CHARACTERS': EULA_RU.length
  };
}

// Проверка наличия ключевых разделов
export function checkEulaSections(language = 'EN') {
  const text = language === 'RU' ? EULA_RU : EULA_EN;
  const sections = [
    'license', 'operation', 'risk', 'waiver', 'liability',
    'data', 'termination', 'amendment', 'governing'
  ];
  
  const foundSections = sections.filter(section => 
    text.toLowerCase().includes(section)
  );
  
  return {
    totalSections: sections.length,
    foundSections: foundSections.length,
    missingSections: sections.filter(s => !foundSections.includes(s)),
    completeness: (foundSections.length / sections.length) * 100
  };
}

